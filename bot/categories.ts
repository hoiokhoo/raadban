/** نرمال‌سازی متن برای تطبیق — حذف اعراب، ی/ک فارسی، نیم‌فاصله → فاصله */
export function normalizeFaForCat(s: string): string {
  return (s || '')
    .replace(/[\u064B-\u0652\u0670]/g, '')
    .replace(/[\u200c\u200f\u200e]/g, ' ')
    .replace(/[يى]/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/ة/g, 'ه')
    .replace(/[أإآ]/g, 'ا')
    .replace(/\s+/g, ' ')
    .toLowerCase()
    .trim();
}

