/** پسوندهای رایج فارسی — «پهپادهای» با کلیدواژهٔ «پهپاد» می‌خورد، «جنگل» با «جنگ» نمی‌خورد */
const FA_SUFFIXES = ['ها', 'های', 'هایی', 'هایشان', 'هایمان', 'هایتان', 'ه', 'ی', 'ای', 'ان', 'مان', 'تان', 'شان', 'تر', 'ترین', 'ش', 'م', 'ت', 'ام', 'ات'];

/** ادامهٔ واژه پس از کلیدواژه فقط پسوند فارسی است؟ (حداکثر دو پسوند پیاپی) */
function isFaSuffix(rest: string, depth = 0): boolean {
  if (!rest) return true;
  if (depth >= 2) return false;
  for (const s of FA_SUFFIXES) {
    if (rest === s) return true;
    if (rest.startsWith(s) && isFaSuffix(rest.slice(s.length), depth + 1)) return true;
  }
  return false;
}

/** تطبیق واژه‌مرزی با پسوند مجاز — کلیدواژه باید واژهٔ مستقل (یا با پسوند رایج) باشد */
function hasWord(normText: string, normWord: string): boolean {
  if (!normWord) return false;
  let start = 0;
  while (true) {
    const at = normText.indexOf(normWord, start);
    if (at < 0) return false;
    const before = at === 0 ? ' ' : normText[at - 1]!;
    const afterAt = at + normWord.length;
    const afterRaw = afterAt >= normText.length ? '' : normText.slice(afterAt);
    const isLetter = (c: string) => /[\p{L}\p{N}]/u.test(c);
    const beforeOk = !isLetter(before);
    const afterOk = !afterRaw || !isLetter(afterRaw[0]!) ? true : isFaSuffix(afterRaw.split(/\s/)[0]!);
    if (beforeOk && afterOk) return true;
    start = at + 1;
  }
}

/** دستهٔ یک متن خبر — دقیقاً یک دسته؛ هیچ تطبیقی → other. تابع خالص تست‌پذیر.
 *  پیمایش به ترتیب CAT_ORDER (اولویت سردبیری) — نه ترتیب اعلان آرایه. */
export function categorizeFa(text: string): CatKey {
  const t = normalizeFaForCat(text);
  if (!t) return 'other';
  for (const k of CAT_ORDER) {
    const words = CAT_ORDER_MAP.get(k);
    if (!words) continue;
    for (const w of words) {
      if (hasWord(t, normalizeFaForCat(w))) return k;
    }
  }
  return 'other';
}

/** نگاشت دسته → کلیدواژه‌ها — از CAT_KEYWORDS ساخته می‌شود */
const CAT_ORDER_MAP: Map<CatKey, string[]> = new Map(CAT_KEYWORDS.map((g) => [g.key, g.words] as const));

/** یک بخش نمایشی کارت — دسته + مواردش */
export interface CatSection<T> {
  cat: CatKey;
  label: string;
  items: T[];
}

/** گروه‌بندی موارد خبری به دسته‌ها به ترتیب اولویت — خواستهٔ ۱۹ نوامبر.
 *  درون هر دسته ترتیب ورودی حفظ می‌شود (ترتیب ورودی از تحلیل هوشمند «مهم‌ترین اول» است —
 *  مرتب‌سازی پایدار)؛ دستهٔ خالی حذف می‌شود. تابع خالص و ژنریک — تست‌پذیر. */
export function groupByCategory<T>(items: T[], catOf: (item: T) => CatKey = (i) => categorizeFa((i as unknown as { text?: string }).text || '')): CatSection<T>[] {
  const buckets = new Map<CatKey, T[]>();
  for (const item of items) {
    const k = catOf(item);
    if (!buckets.has(k)) buckets.set(k, []);
    buckets.get(k)!.push(item);
  }
  const out: CatSection<T>[] = [];
  for (const k of CAT_ORDER) {
    const b = buckets.get(k);
    if (!b || b.length === 0) continue;
    out.push({ cat: k, label: CAT_LABELS[k], items: b });
  }
  return out;
}
