// ---------- مدل داده — دفتر حافظهٔ شبانه ----------

/** یک تحلیل شبانهٔ ذخیره‌شده — حافظهٔ پایدار ربات (state در ریپو کامیت می‌شود) */
export interface NightlyAnalysis {
  /** کلید روز تهران «2026-11-12» — ضدتکرار و مرتب‌سازی */
  dateKey: string;
  at: string; // ISO
  /** متن کامل پیام ارسال‌شده (بدون پانوشت 🧷) */
  text: string;
  /** خلاصهٔ حافظهٔ همان روز (پانوشت 🧷) — سوخت شب‌های بعد */
  summary?: string;
  provider?: string;
  items: number;
}

/** سقف حافظهٔ شبانه — ۶۰ روز (~دو ماه تاریخ) */
export const NIGHTLY_HISTORY_CAP = 60;
/** چند روز آخرِ حافظه هر شب به مدل خوانده می‌شود */
export const NIGHTLY_MEMORY_DAYS = 14;
/** سقف نویسهٔ خلاصهٔ هر روز در بلوک حافظه */
export const NIGHTLY_MEMORY_CHARS = 600;
/** نشانگر پانوشت حافظه در خروجی مدل */
export const MEMORY_FOOTER_TAG = '🧷';

/** افزودن تحلیل شبانه به دفتر — تحلیل دوبارهٔ همان روز جایگزین قبلی می‌شود؛ مرتب بر تاریخ؛ سقف ۶۰ روز. تابع خالص. */
export function appendNightlyAnalysis(list: NightlyAnalysis[], a: NightlyAnalysis): NightlyAnalysis[] {
  const out = (list || []).filter((x) => x && typeof x.dateKey === 'string' && x.dateKey && x.dateKey !== a.dateKey);
  out.push({ ...a, text: (a.text || '').trim(), summary: (a.summary || '').trim() || undefined });
  out.sort((x, y) => x.dateKey.localeCompare(y.dateKey));
  return out.slice(Math.max(0, out.length - NIGHTLY_HISTORY_CAP));
}

/** تاریخ شمسی نمایشی یک کلید روز — «۲۱ آبان ۱۴۰۵» (Intl/ICU — بدون محاسبهٔ دستی) */
export function faDateOfKey(dateKey: string): string {
  const [y, m, d] = dateKey.split('-').map(Number);
  if (!y || !m || !d) return '';
  try {
    return new Intl.DateTimeFormat('fa-IR-u-ca-persian', {
      timeZone: 'Asia/Tehran', year: 'numeric', month: 'long', day: 'numeric',
    }).format(Date.UTC(y, m - 1, d, 12));
  } catch {
    return '';
  }
}

/** جداکردن پانوشت حافظهٔ «🧷» از متن پیام — تابع خالص تست‌پذیر.
 *  پانوشت نبود → کل متن بدنه است و خلاصه خالی (شب بعد از آغاز متن خلاصه ساخته می‌شود).
 *  متن فقط-پانوشت → قابل اعتماد نیست؛ کل متن بدنه و خلاصه خالی. */
export function splitMemoryFooter(text: string): { body: string; summary: string } {
  const t = (text || '').trim();
  if (!t) return { body: '', summary: '' };
  const idx = t.lastIndexOf(MEMORY_FOOTER_TAG);
  if (idx < 0) return { body: t, summary: '' };
  const body = t.slice(0, idx).trim();
  let summary = t.slice(idx + MEMORY_FOOTER_TAG.length).trim();
  summary = summary.replace(/^(خلاصهٔ?\s*حافظه|خلاصهٔ?\s*شبانه)\s*[:：\-—]?\s*/, '').trim();
  if (!body) return { body: t, summary: '' };
  return { body, summary: summary.slice(0, 700) };
}

/** استخراج قطعی خلاصهٔ حافظه از بخش‌های خودِ تحلیل — پشتیبانِ نبودِ پانوشت 🧷 (برخی تأمین‌کننده‌ها
 *  پانوشت را نمی‌نویسند): عنوان 🧭 + پانوراما 📊 + نتیجه‌گیری 🔮 — همه از متنِ واقعی تحلیل،
 *  بدون هیچ چیز ساختگی. تابع خالص تست‌پذیر. */
export function memorySummaryOf(body: string, maxChars = 700): string {
  const t = (body || '').trim();
  if (!t) return '';
  const section = (start: string, end: string): string => {
    const s = t.indexOf(start);
    if (s < 0) return '';
    const from = s + start.length;
    const e = end ? t.indexOf(end, from) : -1;
    return t.slice(from, e > 0 ? e : undefined).trim();
  };
  const titleLine = t.split('\n').find((l) => l.trim().startsWith('🧭'))?.replace(/^🧭\s*/, '').trim() || '';
  const panorama = section('📊', '🗂');
  const conclusion = section('🔮', '🗞');
  const parts = [titleLine && `عنوان: ${titleLine}`, panorama && `پانوراما: ${panorama}`, conclusion && `نتیجه‌گیری: ${conclusion}`].filter(Boolean);
  return parts.join('\n').replace(/\n{2,}/g, '\n').slice(0, maxChars).trim();
}

/** بلوک حافظهٔ روزهای پیشین برای ورودی مدل — خلاصهٔ تاریخ‌دار هر روز؛ کهن‌ترین اول (روایت زمانی).
 *  خالی → پیام صادقانهٔ «اولین شب». تابع خالص تست‌پذیر. */
export function buildNightlyMemoryBlock(
  analyses: NightlyAnalysis[],
  maxDays = NIGHTLY_MEMORY_DAYS,
  maxCharsEach = NIGHTLY_MEMORY_CHARS
): string {
  if (!analyses || analyses.length === 0) return '(اولین شب این دوره است — حافظهٔ روزهای پیشین موجود نیست.)';
  const recent = analyses.slice(-maxDays);
  return recent
    .map((a) => {
      const base = (a.summary || '').trim() || (a.text || '').trim();
      const s = base.slice(0, maxCharsEach).replace(/\s+/g, ' ').trim();
      const weekday = weekdayFaOf(a.dateKey, 'Asia/Tehran');
      const fa = faDateOfKey(a.dateKey);
      return `— ${[weekday, fa].filter(Boolean).join(' ')} (${a.dateKey}): ${s}`;
    })
    .join('\n');
}

// ---------- آرشیو روزانه ----------

/** برش رویدادهای «امروز» از آرشیو روزانه — بر پایهٔ تاریخ تهرانِ زمانِ هر رویداد؛ تازه‌ترین اول.
 *  رویداد بی‌زمان معتبر حذف می‌شود (صادقانه). تابع خالص تست‌پذیر. */
export function todayPoolSlice(pool: PoolItem[], todayKey: string, tz = 'Asia/Tehran'): PoolItem[] {
  return (pool || [])
    .filter((p) => {
      if (!p || !p.id || !p.text) return false;
      const t = Date.parse(p.at || '');
      return Number.isFinite(t) && dateKeyOf(t, tz) === todayKey;
    })
    .sort((a, b) => Date.parse(b.at || '') - Date.parse(a.at || ''));
}

