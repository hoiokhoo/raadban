/**
 * مقیاس رندر SVG→PNG/فریم — خواستهٔ کاربر ۲۴ نوامبر ۲۰۲۶:
 * «کیفیت عکسهای حاوی خبر و هواشناسی و توییت و قیمت خودرو و... کمه، بیشترش کن که
 * تار نشه با زوم کردن».
 *
 * رندر SVG با sharp/librsvg در density=72 یک‌به‌یک (۱×) پیکسل می‌سازد؛ density=144
 * همان SVG را با ۲× خطوط پیکسلی می‌شکند (متن برداری تار نمی‌شود). سقف سخت بله
 * (خانوادهٔ تلگرام) برای عکس ~۱۰٬۰۰۰px مجموع عرض+ارتفاع است — پس مقیاس با اندازهٔ
 * کارت سازگار انتخاب می‌شود: کارت بلند به ۱٫۵× یا همان ۱× برمی‌گردد تا بله ردش نکند.
 * خالص و تست‌پذیر.
 */

/** سقف امن مجموع عرض+ارتفاع عکس بله (حد تلگرام ~۱۰٬۰۰۰px) */
export const BALE_DIM_SUM_MAX = 9800;

/** تراکم پایه (۱×) — همان پیش‌فرض پیشین؛ برای سازگاری تست‌ها */
export const DENSITY_1X = 72;
/** تراکم ۱٫۵× */
export const DENSITY_15X = 108;
/** تراکم ۲× — متن برداری در زوم تار نمی‌شود */
export const DENSITY_2X = 144;

/** تراکم رندر مناسب برای یک SVG با ابعاد داده‌شده — بزرگ‌ترین مقیاسی که بله می‌پذیرد.
 *  ابعاد نامعتبر → همان ۱×. خالص و تست‌پذیر. */
export function renderDensityFor(w: number, h: number): number {
  if (!Number.isFinite(w) || !Number.isFinite(h) || w <= 0 || h <= 0) return DENSITY_1X;
  if ((w * 2 + h * 2) <= BALE_DIM_SUM_MAX) return DENSITY_2X;
  if (w * 1.5 + h * 1.5 <= BALE_DIM_SUM_MAX) return DENSITY_15X;
  return DENSITY_1X;
}
