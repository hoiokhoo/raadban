/**
 * مقیاس رندر SVG→PNG/فریم — خواستهٔ کاربر ۲۴ نوامبر ۲۰۲۶:
 * «کیفیت عکسهای حاوی خبر و هواشناسی و توییت و قیمت خودرو و... کمه، بیشترش کن که
 * تار نشه با زوم کردن».
 *
 * خواستهٔ کاربر ۲۵ نوامبر ۲۰۲۶: «عکسها کیفیتشون کمه … اگر نمیشه عکس رو با کیفیت‌تر کرد،
 * تعداد اخبار یا توییتهای هر عکس رو کمتر کن، تعداد عکسها رو بیشتر» — نردبان ۳×:
 * کارت‌های کوتاه (خبر ۸ردیفی/متن کامل/هواشناسی) در ۳× رندر می‌شوند (۳۲۴۰px عرض)؛
 * بلندترها در ۲×؛ ترکیب «کارت کوچک‌تر + تراکم بالاتر» = شارپ‌تر با زوم.
 *
 * رندر SVG با sharp/librsvg در density=72 یک‌به‌یک (۱×) پیکسل می‌سازد؛ density=144
 * همان SVG را با ۲× خطوط پیکسلی می‌شکند و 216=۳× (متن برداری تار نمی‌شود). سقف سخت بله
 * (خانوادهٔ تلگرام) برای عکس ~۱۰٬۰۰۰px مجموع عرض+ارتفاع است — پس مقیاس با اندازهٔ
 * کارت سازگار انتخاب می‌شود: کارت بلند به ۱٫۵× یا همان ۱× برمی‌گردد تا بله ردش نکند.
 * خالص و تست‌پذیر.
 */

/** سقف امن مجموع عرض+ارتفاع عکس بله (حد تلگرام ~۱۰٬۰۰۰px) */
export const BALE_DIM_SUM_MAX = 9800;

/** تراکم پایه (۱×) — همان پیش‌فرض پیشین؛ برای سازگاری تست‌ها */
export const DENSITY_1X = 72;
/** تراکم ۱٫۵× */
export const DENSITY_15X = 108;
/** تراکم ۲× — متن برداری در زوم تار نمی‌شود */
export const DENSITY_2X = 144;
/** تراکم ۳× — کارت کوتاه؛ ۳۲۴۰px عرض — خواستهٔ ۲۵ نوامبر (شارپ‌تر با زوم) */
export const DENSITY_3X = 216;

/** تراکم رندر مناسب برای یک SVG با ابعاد داده‌شده — بزرگ‌ترین مقیاسی که بله می‌پذیرد:
 *  ۳× → ۲× → ۱٫۵× → ۱×. ابعاد نامعتبر → همان ۱×. خالص و تست‌پذیر. */
export function renderDensityFor(w: number, h: number): number {
  if (!Number.isFinite(w) || !Number.isFinite(h) || w <= 0 || h <= 0) return DENSITY_1X;
  if (w * 3 + h * 3 <= BALE_DIM_SUM_MAX) return DENSITY_3X;
  if (w * 2 + h * 2 <= BALE_DIM_SUM_MAX) return DENSITY_2X;
  if (w * 1.5 + h * 1.5 <= BALE_DIM_SUM_MAX) return DENSITY_15X;
  return DENSITY_1X;
}

/** تراکم فریم‌های گیف — سقف ۲×: انکود GIF از فریم ۳× (۲۵فریمی/۱۲فریمی) هم سنگین
 *  و هم فراتر از سقف حجم ۸MB می‌رود؛ PNG بدونِ سقفِ حجم GIF است و ۳× می‌گیرد.
 *  خواستهٔ ۲۵ نوامبر (کیفیت) بدون قربانی‌کردن متحرک‌بودن. خالص و تست‌پذیر. */
export function renderGifDensityFor(w: number, h: number): number {
  return Math.min(renderDensityFor(w, h), DENSITY_2X);
}
